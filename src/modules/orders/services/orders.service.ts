import { Inject, Injectable, NotFoundException } from '@nestjs/common'
import { computeDueDate } from '@/shared/billing/billing-scheduler'
import { deriveBillingStatus } from '@/shared/billing/billing-status'
import { OutboxRelayService } from '@/shared/events/outbox-relay.service'
import type { IdempotencyRequest } from '@/shared/idempotency/idempotency'
import { hashRequest } from '@/shared/idempotency/request-hash'
import {
	type CreateOrderBillingData,
	ORDER_REPOSITORY,
	type OrderRepository,
	type OrderSource,
	type OrderWithRelations,
} from '@/shared/repositories/order.repository'
import { TenantContext } from '@/shared/tenant/tenant.context'
import { CustomersService } from '../../customers/services/customers.service'
import type { CreateOrderDto, OrderItemInputDto } from '../dto/create-order.dto'

export const ORDER_IDEMPOTENCY_SCOPES = {
	dashboard: 'orders.create',
	storefront: 'catalog.orders.create',
} as const

export interface PlaceOrderItem {
	product_id: number
	quantity: number
	unit_price: number
	discount: number
}

/** Everything `place` needs; callers have already resolved prices and the customer. */
export interface PlaceOrderInput {
	customerId: string
	items: PlaceOrderItem[]
	notes?: string
	source: OrderSource
	metadata?: Record<string, unknown>
	trackingToken?: string
	idempotency?: IdempotencyRequest
}

@Injectable()
export class OrdersService {
	constructor(
		@Inject(ORDER_REPOSITORY) private readonly orderRepository: OrderRepository,
		private readonly tenantContext: TenantContext,
		private readonly customersService: CustomersService,
		private readonly outboxRelay: OutboxRelayService,
	) {}

	/**
	 * Dashboard order. The number is generated by the server: a client-sent
	 * `order_number` (deprecated) is ignored, and kept out of the idempotency hash so
	 * an old client retrying with a fresh number still replays.
	 */
	async create(dto: CreateOrderDto, idempotencyKey?: string): Promise<OrderWithRelations> {
		const { order_number: _ignored, ...body } = dto
		return this.place({
			customerId: dto.customer_id,
			items: dto.items,
			notes: dto.notes,
			source: 'dashboard',
			idempotency: idempotencyKey
				? {
						scope: ORDER_IDEMPOTENCY_SCOPES.dashboard,
						key: idempotencyKey,
						requestHash: hashRequest(body),
					}
				: undefined,
		})
	}

	/**
	 * The single order write path (dashboard and storefront). Must run in the seller's
	 * tenant context. Totals, the per-sale charge, numbering, stock, the order.created
	 * event and the Idempotency-Key all go through one repository transaction; the
	 * notifications follow from the event.
	 */
	async place(input: PlaceOrderInput): Promise<OrderWithRelations> {
		const sellerId = this.tenantContext.requireSellerId()

		// A line's discount is client-supplied and only validated as nonnegative, so
		// clamp it to the line value (unit_price * quantity). This keeps every line
		// total >= 0 and, since order.discount is the sum of these, the order total
		// can never go negative. The clamped discount is what we persist so the stored
		// discount and total stay consistent.
		const pricedItems = input.items.map((it) => {
			const lineValue = it.unit_price * it.quantity
			const discount = Math.min(it.discount, lineValue)
			return {
				product_id: it.product_id,
				quantity: it.quantity,
				unit_price: it.unit_price,
				discount,
				total: lineValue - discount,
				lineValue,
			}
		})

		const subtotal = pricedItems.reduce((acc, it) => acc + it.lineValue, 0)
		const discount = pricedItems.reduce((acc, it) => acc + it.discount, 0)
		const total = subtotal - discount

		// Computed BEFORE the write so the repository persists it atomically with the
		// order. The billing number is assigned in the transaction (COB-n = PED-n).
		const billing = await this.buildBillingData(input.customerId, total)

		const { orderId, replayed } = await this.orderRepository.create({
			seller_id: sellerId,
			customer_id: input.customerId,
			notes: input.notes,
			subtotal,
			discount,
			total,
			items: pricedItems.map(({ lineValue: _lineValue, ...it }) => it),
			source: input.source,
			allowOversell: input.source === 'dashboard',
			metadata: input.metadata,
			tracking_token: input.trackingToken,
			billing,
			idempotency: input.idempotency,
		})

		// Run the order.created effects now rather than on the next relay tick.
		if (!replayed) await this.outboxRelay.kick()

		const order = await this.orderRepository.findById(orderId)
		if (!order) throw new NotFoundException('Pedido não encontrado')
		return order
	}

	// Returns the charge to persist alongside the order, or undefined when the
	// customer is not on per_sale billing (periodic modes are handled by the
	// scheduled sync). The customer lookup is a read, safe to run before the write.
	private async buildBillingData(
		customerId: string,
		total: number,
	): Promise<CreateOrderBillingData | undefined> {
		const customer = await this.customersService.findOne(customerId)
		if (customer.billing_mode !== 'per_sale') return undefined

		const dueDate = computeDueDate(customer.billing_mode, customer.billing_day)

		return {
			total_amount: total,
			paid_amount: 0,
			payment_method: 'cash',
			...deriveBillingStatus(0, total),
			due_date: dueDate ?? undefined,
		}
	}

	async addItem(orderId: number, item: OrderItemInputDto) {
		// Clamp the line discount to the line value so the item total can't go
		// negative (mirrors the rule in create). The repo recomputes the order
		// totals from the persisted items, so a clamped discount keeps them consistent.
		const lineValue = item.unit_price * item.quantity
		const discount = Math.min(item.discount ?? 0, lineValue)
		return this.orderRepository.addItem({
			order_id: orderId,
			product_id: item.product_id,
			quantity: item.quantity,
			unit_price: item.unit_price,
			discount,
			total: lineValue - discount,
		})
	}

	async findById(id: number) {
		return this.orderRepository.findById(id)
	}

	async findAll() {
		return this.orderRepository.findAll({})
	}

	async findEvents(id: number) {
		const events = await this.orderRepository.findEvents(id)
		if (!events) throw new NotFoundException('Pedido não encontrado')
		return events
	}

	async updateStatus(id: number, status: string) {
		// Propagate only cancellation to billing — delivery is not payment. Tenant
		// ownership, stock restoration and 404-on-missing are enforced in the repository.
		const billingUpdate =
			status === 'canceled' ? { status: 'canceled', payment_status: 'canceled' } : undefined

		const order = await this.orderRepository.updateStatus(id, status, billingUpdate)
		await this.outboxRelay.kick()
		return order
	}

	async delete(id: number) {
		const order = await this.orderRepository.delete(id)
		await this.outboxRelay.kick()
		return order
	}
}
